// Command genloop generates the checked interpreter loop, checked_gen.go, from the fast
// loop in fast.go, so that the two can never drift apart. The checked loop indexes code,
// constants, hints, upvalues and registers through bounds-checked slices instead of raw
// pointers.
//
// In fast.go, a block between //gen:fast and //gen:checked is replaced by the commented-out
// lines between //gen:checked and //gen:end. Everywhere else the rewrites are mechanical:
// pc becomes an index into code, and the accessors become their checked versions.
//
//	go generate (or: go run ./internal/cmd/genloop)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

var rewrites = []struct {
	re   *regexp.Regexp
	with string
}{
	{regexp.MustCompile(`func \(ex \*executor\) fast\(\) exit`), "func (ex *executor) checkedLoop() exit"},
	{regexp.MustCompile(`\*\(\*uint32\)\(pc\)`), "code[pc]"},
	{regexp.MustCompile(`pc = unsafe\.Add\(pc, 4\)`), "pc++"},
	{regexp.MustCompile(`pc = unsafe\.Add\(pc, (.+)\*4\)`), "pc += $1"},
	{regexp.MustCompile(`\bkAt\(`), "kAtChecked("},
	{regexp.MustCompile(`\bhintAt\(`), "hintAtChecked("},
	{regexp.MustCompile(`\bupAt\(`), "upAtChecked("},
	{regexp.MustCompile(`\bkhashAt\(`), "khashAtChecked("},
}

func generate(src []byte) ([]byte, error) {
	text := string(src)
	// keep only the loop function
	start := strings.Index(text, "//go:noinline\nfunc (ex *executor) fast() exit {")
	if start < 0 {
		return nil, fmt.Errorf("fast() not found")
	}
	body := text[start:]
	if end := strings.Index(body, "\n}\n"); end >= 0 {
		body = body[:end+3]
	}
	var out []string
	mode := ""
	for _, line := range strings.Split(body, "\n") {
		switch strings.TrimSpace(line) {
		case "//gen:fast":
			mode = "fast"
			continue
		case "//gen:checked":
			mode = "checked"
			continue
		case "//gen:end":
			mode = ""
			continue
		}
		switch mode {
		case "fast":
			continue
		case "checked":
			t := strings.TrimLeft(line, "\t ")
			if !strings.HasPrefix(t, "//") {
				return nil, fmt.Errorf("checked block line is not a comment: %q", line)
			}
			out = append(out, strings.TrimPrefix(t, "//"))
			continue
		}
		for _, r := range rewrites {
			line = r.re.ReplaceAllString(line, r.with)
		}
		out = append(out, line)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/cmd/genloop from fast.go; DO NOT EDIT.\n\n")
	b.WriteString("package glua\n\nimport (\n\t\"math\"\n\t\"sync/atomic\"\n\t\"unsafe\"\n)\n\n")
	b.WriteString("// checkedLoop is fast with bounds-checked code, constants, hints, upvalues and registers.\n")
	b.WriteString(strings.Join(out, "\n"))
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%v\n%s", err, b.Bytes())
	}
	return formatted, nil
}

func main() {
	check := flag.Bool("check", false, "fail if checked_gen.go is not up to date")
	flag.Parse()
	src, err := os.ReadFile("fast.go")
	if err != nil {
		fail(err)
	}
	gen, err := generate(src)
	if err != nil {
		fail(err)
	}
	if *check {
		cur, _ := os.ReadFile("checked_gen.go")
		if !bytes.Equal(cur, gen) {
			fail(fmt.Errorf("checked_gen.go is out of date: run go generate"))
		}
		return
	}
	if err := os.WriteFile("checked_gen.go", gen, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genloop:", err)
	os.Exit(1)
}
